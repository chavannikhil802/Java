class Demo {
    public static void main(String[] args) {
        int i = 0;

        // PRINT 1 TO 10 USING WHILE LOOP
        while(i <= 10) {
            System.out.println(i);
            i++;
        }

        i = 0;
        System.out.println("--------------------------");
        while(i++ <= 10) {
            System.out.println(i);
        }

    }
}