public class Demo2 {
    public static void main(String[] args) {
        int i = 11;

        // DO-WHILE IS USED IN MENU ITEM SELECTION

        // DO-WHILE LOOP EXECUTES FOR THE FIRST TIME
        // IRRESPECTIVE OF THE CONDITION
        do {
            System.out.println(i);
            i++;
        }
        while(i <= 10);
    }
}
